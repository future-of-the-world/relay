"""relay sync: write what Claude Code loads from the rules and the active profile.

- ~/.claude/CLAUDE.md (the global target in projects.toml): the rules the
  active profile loads in full, every other rule as title + gist + path.
- each project's CLAUDE.local.md (a target in projects.toml): the rules that
  project adds; never committed (added to .git/info/exclude).
- plugins/*/agents/*.md: the shared role texts assembled into their marked
  regions (relay_roles, source only), then the model and effort of each tier
  from the profile, in the source and in every installed copy of the plugin.

A rule is rules/<name>.md: `# Title`, `> gist`, body. Generated files carry a
marker; a file without it is never overwritten unless --adopt.
"""

import json
import os
import re
import subprocess

import relay_roles
from relay_config import ROOT, claude_dir, projects_file, read_toml

MARK = "<!-- Generated by relay (relay sync). Edit rules/ and profiles/active.toml, not this file. -->"

# The header relay wrote under its old name (~/principles): still relay's own file.
OLD_MARK = "Generated by ~/principles (bin/principles sync)"


class Fail(Exception):
    pass


def rules():
    found = {}
    folder = os.path.join(ROOT, "rules")
    for name in sorted(os.listdir(folder)):
        if not name.endswith(".md"):
            continue
        text = open(os.path.join(folder, name), encoding="utf-8").read()
        lines = text.split("\n")
        if len(lines) < 2 or not lines[0].startswith("# ") or not lines[1].startswith("> "):
            raise Fail(f"rules/{name}: the first two lines must be '# Title' and '> gist'")
        found[name[:-3]] = {"title": lines[0][2:].strip(), "gist": lines[1][2:].strip(),
                            "body": "\n".join(lines[2:]).strip("\n"), "path": os.path.join(folder, name)}
    return found


def targets():
    path = projects_file()
    data = read_toml(path) if os.path.isfile(path) else {}
    out = {}
    for name, spec in data.items():
        file = spec["file"]
        if file.startswith("~/.claude/"):
            file = os.path.join(claude_dir(), file[len("~/.claude/"):])
        out[name] = dict(spec, file=os.path.expanduser(file))
    return out


def render_target(name, spec, all_rules, profile):
    load = list(spec.get("load", []))
    if name == "global":
        load = list(profile.get("rules", {}).get("load", [])) + [r for r in load if r not in profile.get("rules", {}).get("load", [])]
    for r in load:
        if r not in all_rules:
            raise Fail(f"{name}: unknown rule '{r}'")
    read = spec.get("read")
    if read is None:
        read = [r for r in all_rules if r not in load and r not in spec.get("skip", [])]
    out = [MARK, "", f"# {spec.get('title', 'Rules this project loads')}", ""]
    if spec.get("intro"):
        out += [spec["intro"].strip(), ""]
    if name == "global":
        out += [f"Active relay profile: **{profile.get('profile', {}).get('name', 'active')}** "
                f"({profile.get('profile', {}).get('description', '')}). Models by tier: "
                + ", ".join(f"{k} {v}" for k, v in profile.get("models", {}).items()) + ".", ""]
        language = spec.get("native_language")
        if isinstance(language, str) and language.strip():
            out += [f"My native language: {language.strip()}.", ""]
    for r in load:
        rule = all_rules[r]
        out += [f"## {rule['title']}", "", rule["body"], ""]
    if read:
        out += ["## Rules to read when they apply", ""]
        for r in read:
            rule = all_rules[r]
            out.append(f"- **{rule['title']}**: {rule['gist']} Full text: `{rule['path']}`.")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def write_target(name, spec, text, adopt=False):
    path = spec["file"]
    if os.path.isfile(path):
        current = open(path, encoding="utf-8").read()
        ours = MARK in current or OLD_MARK in current
        if not ours and not adopt:
            raise Fail(f"{path} was not written by relay; run `relay sync --adopt {name}` to take it over (a backup is kept)")
        if current == text:
            return "unchanged"
        if not ours:
            os.replace(path, path + ".before-relay")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(text)
    if os.path.basename(path) == "CLAUDE.local.md":
        exclude_from_git(os.path.dirname(path), "CLAUDE.local.md")
    return "written"


def exclude_from_git(root, name):
    try:
        git_dir = subprocess.run(["git", "-C", root, "rev-parse", "--git-common-dir"], capture_output=True, text=True, timeout=5).stdout.strip()
    except Exception:
        return
    if not git_dir:
        return
    exclude = os.path.join(root if not os.path.isabs(git_dir) else "", git_dir, "info", "exclude")
    exclude = os.path.normpath(exclude)
    os.makedirs(os.path.dirname(exclude), exist_ok=True)
    lines = open(exclude, encoding="utf-8").read().splitlines() if os.path.isfile(exclude) else []
    if name not in lines:
        with open(exclude, "a", encoding="utf-8") as handle:
            handle.write(name + "\n")


