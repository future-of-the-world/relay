def set_frontmatter(text, updates):
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return text
    block = m.group(1)
    for key, value in updates.items():
        if re.search(rf"(?m)^{re.escape(key)}:", block):
            block = re.sub(rf"(?m)^{re.escape(key)}:.*$", f"{key}: {value}", block)
        else:
            block += f"\n{key}: {value}"
    return "---\n" + block + "\n---\n" + text[m.end():]


def sync_agents(profile, extra_dirs=(), dry=False):
    """Rewrite model/effort per tier in the agents: the source and installed copies. dry: only list them."""
    folders = []
    for plugin in sorted(os.listdir(os.path.join(ROOT, "plugins"))):
        folders.append(os.path.join(ROOT, "plugins", plugin, "agents"))
        folders += [os.path.join(d, "agents") for d in installed_plugin_dirs(plugin)]
    folders += list(extra_dirs)
    changed = []
    for folder in folders:
        if not os.path.isdir(folder):
            continue
        for name in sorted(os.listdir(folder)):
            if not name.endswith(".md"):
                continue
            path = os.path.join(folder, name)
            text = open(path, encoding="utf-8").read()
            m = re.search(r"(?m)^relay-tier:\s*(\S+)", text)
            if not m:
                continue
            tier = m.group(1)
            updates = {}
            if profile.get("models", {}).get(tier):
                updates["model"] = profile["models"][tier]
            if profile.get("effort", {}).get(tier):
                updates["effort"] = profile["effort"][tier]
            new = set_frontmatter(text, updates)
            if new != text:
                if not dry:
                    with open(path, "w", encoding="utf-8") as handle:
                        handle.write(new)
                changed.append(path)
    return changed


def installed_plugin_dirs(plugin):
    reg = os.path.join(claude_dir(), "plugins", "installed_plugins.json")
    try:
        with open(reg, encoding="utf-8") as handle:
            plugins = json.load(handle).get("plugins", {})
    except (OSError, ValueError):
        return []
    out = []
    for key, entries in plugins.items():
        if key.split("@")[0] != plugin:
            continue
        for e in entries if isinstance(entries, list) else []:
            if isinstance(e, dict) and e.get("installPath") and os.path.isdir(e["installPath"]):
                out.append(e["installPath"])
    return out


REFUSED = "refused: "


def refused(results):
    """The names of the targets sync refused to write."""
    return [name for name, _, state in results if state.startswith(REFUSED)]


def sync(profile, only=None, adopt=None, dry=False):
    all_rules = rules()
    results = []
    for name, spec in targets().items():
        if only and name not in only:
            continue
        text = render_target(name, spec, all_rules, profile)
        if dry:
            current = open(spec["file"], encoding="utf-8").read() if os.path.isfile(spec["file"]) else ""
            results.append((name, spec["file"], "unchanged" if current == text else "would write"))
        else:
            try:
                state = write_target(name, spec, text, adopt=(adopt == name or adopt == "all"))
            except Fail as error:   # one refused file must not stop the others
                state = REFUSED + str(error)
            results.append((name, spec["file"], state))
    if not only or "agents" in only:
        try:
            assembled = relay_roles.assemble_detail(ROOT, dry=dry)
        except relay_roles.RolesError as error:
            raise Fail(str(error))
        for path, regions in assembled:
            names = ", ".join(f"relay:{kind} {name}" for kind, name in regions)
            results.append(("agents", os.path.relpath(path, ROOT), ("would rewrite " if dry else "rewrote ") + names))
        changed = sync_agents(profile, dry=dry)
        state = (f"would assemble {len(assembled)}, would set model/effort in {len(changed)}" if dry
                 else f"assembled {len(assembled)}, set model/effort in {len(changed)}")
        results.append(("agents", "plugins/*/agents with a relay-tier (+ installed copies)", state))
    return results


def check(profile):
    """Names of targets whose file is out of date."""
    all_rules = rules()
    stale = []
    for name, spec in targets().items():
        text = render_target(name, spec, all_rules, profile)
        current = open(spec["file"], encoding="utf-8").read() if os.path.isfile(spec["file"]) else ""
        if current != text:
            stale.append((name, spec["file"]))
    return stale
