"""relay sync: write what Claude Code loads from the rules and the active profile.

- ~/.claude/CLAUDE.md (the global target in projects.toml): the rules the
  active profile loads in full, every other rule as title + gist + path.
- each project's CLAUDE.local.md (a target in projects.toml): the rules that
  project adds; never committed (added to .git/info/exclude).
- plugins/*/agents/*.md: the shared role texts assembled into their marked
  regions (relay_roles, source only), then the model and effort of each tier
  from the profile, in the source and in every installed copy of the plugin.

A rule is rules/<name>.md: `# Title`, `> gist`, body. Generated files carry a
marker; a file without it is never overwritten unless --adopt.
"""

import json
import os
import re
import subprocess
import sys
import tomllib

import relay_kit
import relay_roles
from relay_config import ROOT, RULE_KEYS, claude_dir, projects_file, read_toml

MARK = "<!-- Generated by relay (relay sync). Edit rules/ and profiles/active.toml, not this file. -->"

# The header relay wrote under its old name (~/principles): still relay's own file.
OLD_MARK = "Generated by ~/principles (bin/principles sync)"


class Fail(Exception):
    pass


def rules():
    """Every rule: its text is read from this checkout; its path names the main checkout, since a linked worktree is removed
    after its merge and the global file must not point into it."""
    import relay_setup  # lazily: relay_setup imports this module too
    found = {}
    folder = os.path.join(ROOT, "rules")
    named = os.path.join(relay_setup.main_checkout(ROOT) or os.path.realpath(ROOT), "rules")
    for name in sorted(os.listdir(folder)):
        if not name.endswith(".md"):
            continue
        text = open(os.path.join(folder, name), encoding="utf-8").read()
        lines = text.split("\n")
        if len(lines) < 2 or not lines[0].startswith("# ") or not lines[1].startswith("> "):
            raise Fail(f"rules/{name}: the first two lines must be '# Title' and '> gist'")
        found[name[:-3]] = {"title": lines[0][2:].strip(), "gist": lines[1][2:].strip(),
                            "body": "\n".join(lines[2:]).strip("\n"), "path": os.path.join(named, name)}
    return found


def targets():
    path = projects_file()
    data = read_toml(path) if os.path.isfile(path) else {}
    out = {}
    for name, spec in data.items():
        file = spec["file"]
        if file.startswith("~/.claude/"):
            file = os.path.join(claude_dir(), file[len("~/.claude/"):])
        spec = dict(spec, file=os.path.expanduser(file))
        if name != "global":   # a project's own settings (lanes, load, read) are in its git, not in the registry
            kit = relay_kit.load(os.path.dirname(spec["file"]))
            relay_kit.warn(kit, "rules")
            written = kit.raw.get("rules")      # only the keys the file sets override the registry; their values are the checked ones
            spec.update({k: kit.get("rules", k) for k in (written if isinstance(written, dict) else {}) if k in RULE_KEYS})
        out[name] = spec
    return out


def spec_methods():
    """{plugin name: flow.json} for every plugin that supplies spec steps (`"slot": "specs"`)."""
    found = {}
    folder = os.path.join(ROOT, "plugins")
    for plugin in sorted(os.listdir(folder)):
        path = os.path.join(folder, plugin, "flow.json")
        if not os.path.isfile(path):
            continue
        with open(path, encoding="utf-8") as handle:
            manifest = json.load(handle)
        if manifest.get("slot") == "specs":
            found[plugin] = manifest
    return found


def project_spec_method(spec):
    """The `[specs] method` of the project a target writes into (its .claude/kit.toml); "none" when unset or unreadable."""
    if "file" not in spec:
        return "none"  # a target with no file has no project folder, so no spec method
    path = os.path.join(os.path.dirname(spec["file"]), ".claude", "kit.toml")
    try:
        with open(path, "rb") as handle:
            method = tomllib.load(handle).get("specs", {}).get("method", "none")
    except (OSError, tomllib.TOMLDecodeError):
        return "none"
    return method if isinstance(method, str) else "none"


def steps_table(manifest):
    """The spec method's steps as the table the project's rules carry, rendered from flow.json `steps`."""
    lines = ["### Spec steps in the change cycle", "",
             "Each step runs at the step of the change cycle it names (the delegate skill, \"Review loop\").", "",
             "| At step | What happens | Skill or agent |", "|---|---|---|"]
    for step in manifest.get("steps", []):
        who = step.get("skill") or step.get("agent") or ""
        lines.append(f"| {step['at']} | {step['does']} | {('`' + who + '`') if who else ''} |")
    lines.append("")
    return lines


LANES_DEFAULT = 4
LANES_MAX = 8


def lanes_of(name: str, spec: dict) -> int:
    """How many changes the project builds at once: kit.toml [rules] `lanes`, 1-8, default 4."""
    value = spec.get("lanes", LANES_DEFAULT)
    if isinstance(value, bool) or not isinstance(value, int) or not 1 <= value <= LANES_MAX:
        raise Fail(f"{name}: kit.toml [rules] lanes must be a whole number from 1 to {LANES_MAX}, got {value!r}")
    return value


WAVE_MIN_DEFAULT = 3
WAVE_MIN_MAX = 6


def wave_min_of(name: str, spec: dict) -> int:
    """How many changes `bin/paid-cost due` lists before the front starts a paid run: kit.toml [rules] `wave_min`, 1-6, default 3."""
    value = spec.get("wave_min", WAVE_MIN_DEFAULT)
    if isinstance(value, bool) or not isinstance(value, int) or not 1 <= value <= WAVE_MIN_MAX:
        raise Fail(f"{name}: kit.toml [rules] wave_min must be a whole number from 1 to {WAVE_MIN_MAX}, got {value!r}")
    return value


def render_target(name, spec, all_rules, profile):
    load = list(spec.get("load", []))
    methods = spec_methods()
    method = None
    if name != "global":
        for r in load:
            if r in methods:
                raise Fail(f"projects.toml [{name}] load names `{r}`: spec rules come from kit.toml [specs]; run `relay setup <dir>`")
        method = project_spec_method(spec)
        if method in methods and method in all_rules:
            load.append(method)
        else:
            method = None
    if name == "global":
        load = list(profile.get("rules", {}).get("load", [])) + [r for r in load if r not in profile.get("rules", {}).get("load", [])]
    for r in load:
        if r not in all_rules:
            raise Fail(f"{name}: unknown rule '{r}'")
    read = spec.get("read")
    if read is None:
        read = [r for r in all_rules if r not in load and r not in spec.get("skip", []) and r not in methods]
    out = [MARK, "", f"# {spec.get('title', 'Rules this project loads')}", ""]
    if spec.get("intro"):
        out += [spec["intro"].strip(), ""]
    if name == "global":
        out += [f"Active relay profile: **{profile.get('profile', {}).get('name', 'active')}** "
                f"({profile.get('profile', {}).get('description', '')}). Models by tier: "
                + ", ".join(f"{k} {v}" for k, v in profile.get("models", {}).items()) + ".", ""]
        language = spec.get("native_language")
        if isinstance(language, str) and language.strip():
            out += [f"My native language: {language.strip()}.", ""]
    if name != "global":
        out += [f"Changes built at once: {lanes_of(name, spec)}.", "",
                f"Paid run starts when `bin/paid-cost due` lists at least: {wave_min_of(name, spec)} changes.", ""]
    for r in load:
        rule = all_rules[r]
        out += [f"## {rule['title']}", "", rule["body"], ""]
        if r == method:
            out += steps_table(methods[method])
    if read:
        out += ["## Rules to read when they apply", ""]
        for r in read:
            rule = all_rules[r]
            out.append(f"- **{rule['title']}**: {rule['gist']} Full text: `{rule['path']}`.")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def refusal(name, path, adopt):
    """The reason sync would not overwrite path (a file relay did not write, no adopt), else None."""
    if adopt or not os.path.isfile(path):
        return None
    current = open(path, encoding="utf-8").read()
    if MARK in current or OLD_MARK in current:
        return None
    return f"{path} was not written by relay; run `relay sync --adopt {name}` to take it over (a backup is kept)"


def write_target(name, spec, text, adopt=False):
    path = spec["file"]
    reason = refusal(name, path, adopt)
    if reason:
        raise Fail(reason)
    if os.path.isfile(path):
        current = open(path, encoding="utf-8").read()
        ours = MARK in current or OLD_MARK in current
        if current == text:
            return "unchanged"
        if not ours:
            os.replace(path, path + ".before-relay")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(text)
    if os.path.basename(path) == "CLAUDE.local.md":
        exclude_from_git(os.path.dirname(path), "CLAUDE.local.md")
    return "written"


def exclude_from_git(root, name):
    try:
        git_dir = subprocess.run(["git", "-C", root, "rev-parse", "--git-common-dir"], capture_output=True, text=True, timeout=5).stdout.strip()
    except Exception:
        return
    if not git_dir:
        return
    exclude = os.path.join(root if not os.path.isabs(git_dir) else "", git_dir, "info", "exclude")
    exclude = os.path.normpath(exclude)
    os.makedirs(os.path.dirname(exclude), exist_ok=True)
    lines = open(exclude, encoding="utf-8").read().splitlines() if os.path.isfile(exclude) else []
    if name not in lines:
        with open(exclude, "a", encoding="utf-8") as handle:
            handle.write(name + "\n")


