"""relay sync writes every target it can and names the ones it refused."""
import os
import shutil
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RELAY = os.path.join(ROOT, "bin", "relay")
OLD_HEADER = "<!-- Generated by ~/principles (bin/principles sync). Edit rules/, not this file. -->\n"


class SyncRefused(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="relay-test-")
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)
        self.a = os.path.join(self.tmp, "a", "CLAUDE.local.md")
        self.b = os.path.join(self.tmp, "b", "CLAUDE.local.md")
        for path in (self.a, self.b):
            os.makedirs(os.path.dirname(path))
        projects = os.path.join(self.tmp, "projects.toml")
        with open(projects, "w") as handle:
            for n, path in (("a", self.a), ("b", self.b)):
                handle.write('[%s]\nfile = "%s"\nload = ["quality-gate"]\nread = []\n\n' % (n, path))
        self.env = dict(os.environ, RELAY_PROJECTS=projects, RELAY_HOME=os.path.join(self.tmp, "home"),
                        CLAUDE_CONFIG_DIR=os.path.join(self.tmp, "claude"), RELAY_ROOT=ROOT, RELAY_SKIP_PAID_DUE="1")

    def sync(self):
        # Named targets only (a and b): the agents are not touched.
        return subprocess.run([sys.executable, RELAY, "sync", "a", "b"], env=self.env, capture_output=True, text=True)

    def put(self, path, text):
        with open(path, "w") as handle:
            handle.write(text)

    def read(self, path):
        with open(path) as handle:
            return handle.read()

    def test_a_refused_target_does_not_stop_the_later_ones(self):
        self.put(self.a, "someone else's file\n")
        self.put(self.b, OLD_HEADER + "stale\n")
        done = self.sync()
        # A is foreign: left as is. B carries a relay header and is stale: rewritten. Exit 1 naming A and --adopt.
        self.assertEqual(self.read(self.a), "someone else's file\n")
        self.assertNotIn("stale", self.read(self.b))
        self.assertEqual(done.returncode, 1)
        self.assertIn("refused a;", done.stderr)
        self.assertIn("--adopt", done.stderr)

    def test_the_old_principles_header_is_rewritten_without_adopt(self):
        self.put(self.a, OLD_HEADER + "stale\n")
        self.put(self.b, OLD_HEADER + "stale\n")
        done = self.sync()
        self.assertEqual(done.returncode, 0, done.stderr)
        self.assertNotIn("~/principles", self.read(self.a))
        self.assertIn("Generated by relay", self.read(self.a))

    def relay(self, *args):
        return subprocess.run([sys.executable, RELAY, *args], env=self.env, capture_output=True, text=True)

    def test_an_unknown_rule_in_one_project_does_not_stop_the_later_ones(self):
        projects = self.env["RELAY_PROJECTS"]
        text = self.read(projects).replace('load = ["quality-gate"]', 'load = ["no-such-rule"]', 1)
        self.put(projects, text)
        self.put(self.a, OLD_HEADER + "old-a\n")
        self.put(self.b, OLD_HEADER + "stale\n")
        done = self.sync()
        # a cannot render (unknown rule): left as is; b is relay's and stale: rewritten; exit 1 names a and the reason.
        self.assertIn("old-a", self.read(self.a))
        self.assertNotIn("stale", self.read(self.b))
        self.assertEqual(done.returncode, 1)
        self.assertIn("refused a;", done.stderr)
        self.assertIn("unknown rule 'no-such-rule'", done.stdout)

    def test_dry_run_says_would_refuse_for_a_foreign_file(self):
        self.put(self.a, "someone else's file\n")
        self.put(self.b, OLD_HEADER + "stale\n")
        done = self.relay("sync", "--dry", "a", "b")
        self.assertIn("a: would refuse:", done.stdout)
        self.assertIn("b: would write", done.stdout)
        self.assertEqual(self.read(self.a), "someone else's file\n")
        # --adopt a: the preview says would write (a is taken over).
        adopted = self.relay("sync", "--dry", "--adopt", "a", "a")
        self.assertIn("a: would write", adopted.stdout)
        self.assertEqual(adopted.returncode, 0, adopted.stderr)

    def _setup(self, global_text, *flags):
        claude = self.env["CLAUDE_CONFIG_DIR"]
        os.makedirs(claude, exist_ok=True)
        gfile = os.path.join(claude, "CLAUDE.md")
        if global_text is not None:
            self.put(gfile, global_text)
        with open(self.env["RELAY_PROJECTS"], "a") as handle:
            handle.write('[global]\nfile = "~/.claude/CLAUDE.md"\nload = []\nread = []\n')
        proj = os.path.join(self.tmp, "proj")
        os.makedirs(proj)
        subprocess.run(["git", "init", "-q", proj], check=True)
        return gfile, self.relay("setup", *flags, proj)

    def test_project_setup_leaves_a_foreign_global_file_alone_and_exits_0(self):
        # decision A: project setup never touches ~/.claude, so the foreign global file is not even looked at.
        gfile, done = self._setup("my own file\n")
        self.assertEqual(self.read(gfile), "my own file\n")
        self.assertEqual(done.returncode, 0, done.stdout + done.stderr)

    def test_project_setup_does_not_rewrite_relays_old_global_file(self):
        gfile, done = self._setup(OLD_HEADER + "old\n")
        self.assertEqual(self.read(gfile), OLD_HEADER + "old\n")
        self.assertEqual(done.returncode, 0, done.stdout + done.stderr)

    def test_no_global_flag_is_gone(self):
        gfile, done = self._setup("my own file\n", "--no-global")
        self.assertEqual(done.returncode, 2, done.stdout + done.stderr)
        self.assertIn("--no-global", done.stderr)
        self.assertEqual(self.read(gfile), "my own file\n")


if __name__ == "__main__":
    unittest.main()
