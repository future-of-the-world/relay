"""relay sync writes every target it can and names the ones it refused."""
import os
import shutil
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RELAY = os.path.join(ROOT, "bin", "relay")
OLD_HEADER = "<!-- Generated by ~/principles (bin/principles sync). Edit rules/, not this file. -->\n"


class SyncRefused(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="relay-test-")
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)
        self.a = os.path.join(self.tmp, "a", "CLAUDE.local.md")
        self.b = os.path.join(self.tmp, "b", "CLAUDE.local.md")
        for path in (self.a, self.b):
            os.makedirs(os.path.dirname(path))
        projects = os.path.join(self.tmp, "projects.toml")
        with open(projects, "w") as handle:
            for n, path in (("a", self.a), ("b", self.b)):
                handle.write('[%s]\nfile = "%s"\nload = ["quality-gate"]\nread = []\n\n' % (n, path))
        self.env = dict(os.environ, RELAY_PROJECTS=projects, RELAY_HOME=os.path.join(self.tmp, "home"),
                        CLAUDE_CONFIG_DIR=os.path.join(self.tmp, "claude"), RELAY_ROOT=ROOT)

    def sync(self):
        # Named targets only (a and b): the agents are not touched.
        return subprocess.run([sys.executable, RELAY, "sync", "a", "b"], env=self.env, capture_output=True, text=True)

    def put(self, path, text):
        with open(path, "w") as handle:
            handle.write(text)

    def read(self, path):
        with open(path) as handle:
            return handle.read()

    def test_a_refused_target_does_not_stop_the_later_ones(self):
        self.put(self.a, "someone else's file\n")
        self.put(self.b, OLD_HEADER + "stale\n")
        done = self.sync()
        # A is foreign: left as is. B carries a relay header and is stale: rewritten. Exit 1 naming A and --adopt.
        self.assertEqual(self.read(self.a), "someone else's file\n")
        self.assertNotIn("stale", self.read(self.b))
        self.assertEqual(done.returncode, 1)
        self.assertIn("refused a;", done.stderr)
        self.assertIn("--adopt", done.stderr)

    def test_the_old_principles_header_is_rewritten_without_adopt(self):
        self.put(self.a, OLD_HEADER + "stale\n")
        self.put(self.b, OLD_HEADER + "stale\n")
        done = self.sync()
        self.assertEqual(done.returncode, 0, done.stderr)
        self.assertNotIn("~/principles", self.read(self.a))
        self.assertIn("Generated by relay", self.read(self.a))


if __name__ == "__main__":
    unittest.main()
