"""Library tests: rules sync."""
import os
import shutil
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))   # unittest from the repo root has only the root on sys.path
from relay_testbase import Base, ROOT  # noqa: E402


class Rules(Base):
    def setUp(self):
        super().setUp()
        # these tests sync into temporary targets; the wait for a green paid run is tested in test_paid_batch.py
        old = os.environ.get("RELAY_SKIP_PAID_DUE"); os.environ["RELAY_SKIP_PAID_DUE"] = "1"
        self.addCleanup(lambda: os.environ.__setitem__("RELAY_SKIP_PAID_DUE", old) if old is not None else os.environ.pop("RELAY_SKIP_PAID_DUE", None))

    def test_sync_writes_global_and_project_files(self):
        import relay_config
        import relay_rules
        profile = relay_config.active_profile()
        # not "agents": that rewrites the repository's own agent files (test_profile_rewrites_tiered_agents_in_a_copy covers it)
        results = relay_rules.sync(profile, only={"global", "demo"})
        states = {n: s for n, _, s in results}
        self.assertEqual(states["global"], "written")
        self.assertEqual(states["demo"], "written")
        self.assertIn("## Quality gate", open(self.project_file).read())
        text = open(os.path.join(self.claude, "CLAUDE.md")).read()
        self.assertIn("Generated by relay", text)
        self.assertIn("## Delegation", text)
        self.assertIn("Rules to read when they apply", text)
        self.assertEqual(relay_rules.check(profile), [])
        with open(self.project_file, "a") as handle:
            handle.write("edited\n")
        self.assertEqual([c[0] for c in relay_rules.check(profile)], ["demo"])

    def test_hand_written_file_is_not_overwritten(self):
        import relay_config
        import relay_rules
        with open(os.path.join(self.claude, "CLAUDE.md"), "w") as handle:
            handle.write("mine\n")
        refused = relay_rules.sync(relay_config.active_profile(), only={"global"})
        self.assertEqual(relay_rules.refused(refused), ["global"])
        self.assertEqual(open(os.path.join(self.claude, "CLAUDE.md")).read(), "mine\n")
        relay_rules.sync(relay_config.active_profile(), only={"global"}, adopt="global")
        self.assertTrue(os.path.isfile(os.path.join(self.claude, "CLAUDE.md.before-relay")))

    def test_profile_rewrites_tiered_agents_in_a_copy(self):
        copy = os.path.join(self.tmp, "agents")
        shutil.copytree(os.path.join(ROOT, "plugins", "delegate", "agents"), copy)
        os.environ["RELAY_ROOT"] = os.path.join(self.tmp, "empty-root")   # no plugins/ there: only extra_dirs are touched
        os.makedirs(os.path.join(self.tmp, "empty-root", "plugins"))
        for m in list(sys.modules):
            if m.startswith("relay_"):
                del sys.modules[m]
        import relay_rules
        changed = relay_rules.sync_agents({"models": {"build": "haiku", "judge": "sonnet"}, "effort": {"judge": "xhigh"}}, extra_dirs=[copy])
        worker = open(os.path.join(copy, "worker.md")).read()
        reviewer = open(os.path.join(copy, "critic.md")).read()
        self.assertIn("model: haiku", worker)
        self.assertIn("model: sonnet", reviewer)
        self.assertIn("effort: xhigh", reviewer)
        self.assertTrue(any(p.endswith("worker.md") for p in changed))
        self.assertIn("model: sonnet", open(os.path.join(ROOT, "plugins", "delegate", "agents", "worker.md")).read())  # source untouched

    def test_set_frontmatter(self):
        import relay_rules
        text = "---\nname: x\nmodel: opus\n---\nbody\n"
        new = relay_rules.set_frontmatter(text, {"model": "sonnet", "effort": "low"})
        self.assertIn("model: sonnet", new)
        self.assertIn("effort: low", new)
        self.assertTrue(new.endswith("body\n"))


class RulesInWorktree(Base):
    def _relay_copy(self):
        import subprocess
        main = os.path.join(self.tmp, "relaycopy")
        os.makedirs(os.path.join(main, "rules"))
        os.makedirs(os.path.join(main, "plugins"))
        open(os.path.join(main, "plugins", ".gitkeep"), "w").close()   # git tracks no empty folder
        with open(os.path.join(main, "rules", "demo-rule.md"), "w") as handle:
            handle.write("# Main title\n> main gist\nbody\n")
        git = ["git", "-C", main, "-c", "user.name=t", "-c", "user.email=t@t"]
        subprocess.run(["git", "init", "-q", main], check=True)
        subprocess.run(git + ["add", "."], check=True)
        subprocess.run(git + ["commit", "-q", "-m", "init"], check=True)
        wt = os.path.join(self.tmp, "relaywt")
        subprocess.run(git + ["worktree", "add", "-q", "-b", "wt/x", wt], check=True)
        return main, wt

    def _global_text(self, root):
        import relay_rules
        relay_rules.ROOT = root
        found = relay_rules.rules()
        spec = {"file": os.path.join(self.tmp, "G.md"), "title": "T", "intro": "I", "load": []}
        return found, relay_rules.render_target("global", spec, found, {})

    def test_full_text_paths_from_a_linked_worktree_name_the_main_checkout(self):
        # The worktree is removed after its merge, so the global file must not name it: every path starts with the main checkout.
        main, wt = self._relay_copy()
        found, text = self._global_text(wt)
        want = os.path.join(os.path.realpath(main), "rules", "demo-rule.md")
        self.assertEqual(found["demo-rule"]["path"], want)
        self.assertIn(f"Full text: `{want}`", text)
        self.assertNotIn(wt, text)

    def test_full_text_paths_in_the_main_checkout_are_unchanged(self):
        main, _ = self._relay_copy()
        found, text = self._global_text(main)
        self.assertEqual(found["demo-rule"]["path"], os.path.join(os.path.realpath(main), "rules", "demo-rule.md"))

    def test_a_symlinked_main_checkout_gives_the_same_path_as_its_worktree(self):
        # Main reached as .../link (symlink) and its worktree must render one string, the resolved main checkout.
        import relay_rules
        main, wt = self._relay_copy()
        link = os.path.join(self.tmp, "link")
        os.symlink(main, link)
        paths = []
        for root in (link, wt):
            relay_rules.ROOT = root
            paths.append(relay_rules.rules()["demo-rule"]["path"])
        self.assertEqual(paths[0], paths[1])
        self.assertEqual(paths[0], os.path.join(os.path.realpath(main), "rules", "demo-rule.md"))

    def test_rule_text_comes_from_the_checkout_being_rendered(self):
        main, wt = self._relay_copy()
        with open(os.path.join(wt, "rules", "demo-rule.md"), "w") as handle:
            handle.write("# Branch title\n> branch gist\nbody\n")
        found, text = self._global_text(wt)
        self.assertEqual((found["demo-rule"]["title"], found["demo-rule"]["gist"]), ("Branch title", "branch gist"))
        self.assertIn("**Branch title**: branch gist", text)


